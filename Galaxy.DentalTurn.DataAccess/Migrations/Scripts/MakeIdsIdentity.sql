-- Script to make id columns identity for tables in public schema
-- Backup DB before running.

-- For each table: admin_users, business_hours, patients, practitioners, services, appointments, practitioner_services

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_class WHERE relname = 'services_id_seq') THEN
	PERFORM 1;
  END IF;
END$$;

-- Helper: for each table, create sequence if needed, assign ids for id=0, and set default

-- services
DO $$
DECLARE m bigint;
BEGIN
  SELECT COALESCE(MAX(id),0) INTO m FROM services;
  IF m < 1 THEN m := 1; END IF;
  EXECUTE format('CREATE SEQUENCE IF NOT EXISTS services_id_seq START WITH %s;', m+1);
  EXECUTE 'ALTER SEQUENCE services_id_seq OWNED BY services.id';
  UPDATE services SET id = nextval('services_id_seq') WHERE id = 0;
  ALTER TABLE services ALTER COLUMN id SET DEFAULT nextval('services_id_seq');
END$$;

